//! Writes the licence texts of every crate built into the Windows exe, for the
//! release zip (`THIRD_PARTY_LICENSES.txt`). Reads `cargo metadata` on stdin:
//!
//!   cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc |
//!       cargo run --example third_party_licenses > THIRD_PARTY_LICENSES.txt
//!
//! Only normal dependencies count (build scripts and tests are not shipped).
//! Crates whose texts are the same are listed together under one copy.

use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::io::Read;
use std::path::Path;

/// A licence file in a crate: `LICENSE-MIT`, `COPYING`, `NOTICE`, and fonts'
/// licences such as `fonts/OFL.txt` (the default egui fonts are embedded).
fn is_licence(rel: &Path) -> bool {
    let name = rel.file_name().and_then(|n| n.to_str()).unwrap_or_default().to_ascii_lowercase();
    let in_fonts = rel.components().any(|c| c.as_os_str().eq_ignore_ascii_case("fonts"));
    ["license", "licence", "copying", "notice", "copyright", "unlicense"].iter().any(|k| name.starts_with(k) || name.contains(&format!("-{k}")))
        || (in_fonts && name.ends_with(".txt"))
}

fn main() {
    let mut input = String::new();
    std::io::stdin().read_to_string(&mut input).expect("cargo metadata on stdin");
    let meta: Value = serde_json::from_str(&input).expect("cargo metadata JSON");
    let packages: HashMap<&str, &Value> = meta["packages"].as_array().unwrap().iter().map(|p| (p["id"].as_str().unwrap(), p)).collect();
    let nodes: HashMap<&str, &Value> = meta["resolve"]["nodes"].as_array().unwrap().iter().map(|n| (n["id"].as_str().unwrap(), n)).collect();
    let root = meta["resolve"]["root"].as_str().expect("run in the OrangeLink folder");

    // Everything reachable from OrangeLink through normal dependencies.
    let mut seen = BTreeSet::new();
    let mut stack = vec![root];
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            continue;
        }
        for dep in nodes[id]["deps"].as_array().into_iter().flatten() {
            let normal = dep["dep_kinds"].as_array().into_iter().flatten().any(|k| k["kind"].is_null());
            if normal {
                stack.push(dep["pkg"].as_str().unwrap());
            }
        }
    }
    seen.remove(root);

    // Licence text -> the crates that carry it.
    let mut by_text: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for id in &seen {
        let p = packages[id];
        let label = format!("{} {} ({})", p["name"].as_str().unwrap(), p["version"].as_str().unwrap(), p["license"].as_str().unwrap_or("see file"));
        let dir = Path::new(p["manifest_path"].as_str().unwrap()).parent().unwrap().to_path_buf();
        let mut files: Vec<_> = walkdir::WalkDir::new(&dir)
            .max_depth(2)
            .into_iter()
            .filter_map(Result::ok)
            .filter(|e| e.file_type().is_file() && is_licence(e.path().strip_prefix(&dir).unwrap()))
            .map(|e| e.into_path())
            .collect();
        files.sort();
        let mut text = String::new();
        for f in &files {
            if let Ok(t) = std::fs::read_to_string(f) {
                text.push_str(&format!("--- {} ---\n{}\n", f.strip_prefix(&dir).unwrap().display(), t.replace("\r\n", "\n").trim_end()));
            }
        }
        if text.is_empty() {
            let repo = p["repository"].as_str().unwrap_or("its crates.io page");
            let authors: Vec<&str> = p["authors"].as_array().into_iter().flatten().filter_map(Value::as_str).collect();
            text = format!(
                "No licence file is included in the published crate. Licence: {}. Authors: {}. Source: {}\n",
                p["license"].as_str().unwrap_or("unknown"),
                if authors.is_empty() { "not listed".to_string() } else { authors.join(", ") },
                repo
            );
        }
        by_text.entry(text).or_default().push(label);
    }

    println!("Third-party licences for the crates built into OrangeLink ({} crates).", seen.len());
    println!("Generated by examples/third_party_licenses.rs from Cargo.lock. Code adapted");
    println!("from other projects is listed in THIRD_PARTY_NOTICES.md.\n");
    for (text, crates) in by_text {
        println!("==============================================================================");
        for c in crates {
            println!("{c}");
        }
        println!("------------------------------------------------------------------------------");
        println!("{text}");
    }
}
